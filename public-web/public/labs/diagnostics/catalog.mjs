function section(id, label, questions) {
  return Object.freeze({ id, label, questions: Object.freeze(questions.map((text, index) => Object.freeze({ id:`${id}_${index + 1}`, text }))) });
}

function pathStep(id, label, prompt) { return Object.freeze({ id, label, prompt }); }

