export function buildNodes() {
  return CONTEXTS.flatMap((context) => LAWS.map((law) => ({
    id: `SEP(${law.id},${context.id})`,
    lawId: law.id,
    contextId: context.id,
    law: law.name,
    context: context.name,
    operator: law.operator,
    question: `В контуре «${context.name}»: ${law.question}`,
  })));
}

