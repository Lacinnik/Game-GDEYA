export function shouldShowOnboarding(storage) {
  try {
    return storage?.getItem(ONBOARDING_KEY) !== "seen";
  } catch {
    return false;
  }
}

export function markOnboardingSeen(storage) {
  try {
    storage?.setItem(ONBOARDING_KEY, "seen");
  } catch {}
}
